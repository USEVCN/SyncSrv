export function storageText(text: string): string {
  if (!/文件源|实时备份|归档备份|合成备份|\b[ABCD]\b/.test(text)) return text;
  return legacyNames.reduce((value, [before, after]) => value.split(before).join(after), text)
    .replace(/(源目录|备份库|归档库|恢复库) +(?=[\u4e00-\u9fff])/g, "$1");
}
